export function getStoredCars() {
  try {
    const saved = localStorage.getItem("rydex_fleet_cars");
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Ensure no transmission or car type fields leak in
        return parsed.map((c) => {
          const { transmission, type, freeCancellation, distanceLimit, ...rest } = c;
          return {
            ...rest,
            seats: Number(c.seats) === 7 ? 7 : 5, // strictly 5 or 7
            ac: c.ac !== false, // default true unless explicitly false
          };
        });
      }
    }
  } catch (e) {
    console.error("Error reading stored fleet", e);
  }
  return initialCars;
}

export function saveStoredCars(carsList) {
  try {
    const sanitized = carsList.map((c) => {
      const { transmission, type, freeCancellation, distanceLimit, ...rest } = c;
      return {
        ...rest,
        seats: Number(c.seats) === 7 ? 7 : 5,
        ac: c.ac !== false,
      };
    });
    localStorage.setItem("rydex_fleet_cars", JSON.stringify(sanitized));
    mongoApi.syncCars(sanitized);
  } catch (e) {
    console.error("Error saving fleet", e);
  }
}

